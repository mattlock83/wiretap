package bundle

import (
	"encoding/base64"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"
	"unicode/utf8"

	"github.com/phrond/wiretap/internal/artifact"
)

const contractPackageProfile = "wiretap-contract-package-v1"

// contractPackageIdentity covers the original bytes, their names, the entry
// point, and the contract language. It is independent of source directories and
// serialization order. It does not claim imports are complete or schemas valid.
type contractPackageIdentity struct {
	Profile string       `json:"profile"`
	Type    string       `json:"type"`
	Root    string       `json:"root"`
	Files   []schemaFile `json:"files"`
}

func opaqueContractType(kind string) bool {
	return kind == "avro" || kind == "asyncapi" || kind == "graphql"
}

func contractFilePath(name string) bool {
	if name == "" || name == "." || !utf8.ValidString(name) || strings.ContainsAny(name, "\\:\x00") || path.IsAbs(name) || path.Clean(name) != name {
		return false
	}
	for _, component := range strings.Split(name, "/") {
		if component == "." || component == ".." || component == "" {
			return false
		}
	}
	// The package manifest is generated by Wiretap and is not a source file.
	return name != "manifest.json"
}

func contractPackageDigest(kind, root string, files []schemaFile) string {
	ordered := append([]schemaFile(nil), files...)
	sort.Slice(ordered, func(i, j int) bool { return ordered[i].Path < ordered[j].Path })
	data, _ := json.Marshal(contractPackageIdentity{Profile: contractPackageProfile, Type: kind, Root: root, Files: ordered})
	return digest(data)
}

func (w *Writer) freezeContractPackage(ref artifact.SchemaRef) (artifact.SchemaRef, error) {
	source := ref.Source
	if source.Type == "omitted" {
		if source.Path != "" || source.URL != "" || source.Content != "" || source.SHA256 != "" || len(source.Files) != 0 {
			return ref, errors.New("omitted schema cannot contain a source")
		}
		return ref, nil
	}
	files := map[string][]byte{}
	root := source.Path
	switch source.Type {
	case "package":
		if source.URL != "" || source.Content != "" || len(source.ImportPaths) != 0 {
			return ref, errors.New("contract package must supply only a root path and explicit files")
		}
		for _, file := range source.Files {
			if !contractFilePath(file.Path) {
				return ref, fmt.Errorf("invalid contract package path %q", file.Path)
			}
			if _, exists := files[file.Path]; exists {
				return ref, fmt.Errorf("duplicate contract package path %q", file.Path)
			}
			var data []byte
			switch file.Encoding {
			case "", "text":
				if !utf8.ValidString(file.Content) {
					return ref, fmt.Errorf("contract file %q is not UTF-8; use base64", file.Path)
				}
				data = []byte(file.Content)
			case "base64":
				var err error
				data, err = base64.StdEncoding.DecodeString(file.Content)
				if err != nil {
					return ref, fmt.Errorf("contract file %q: %w", file.Path, err)
				}
			default:
				return ref, fmt.Errorf("unsupported contract file encoding %q", file.Encoding)
			}
			files[file.Path] = data
		}
	case "file", "inline":
		if source.URL != "" || len(source.Files) != 0 || len(source.ImportPaths) != 0 {
			return ref, errors.New("multi-file contracts require an explicit package source")
		}
		if source.Type == "file" {
			if source.Content != "" || source.Path == "" {
				return ref, errors.New("file contract requires a path without inline content")
			}
			data, err := os.ReadFile(source.Path)
			if err != nil {
				return ref, err
			}
			root = filepath.Base(source.Path)
			files[root] = data
		} else {
			if root == "" {
				root = "schema." + ref.Type
			}
			files[root] = []byte(source.Content)
		}
	default:
		return ref, fmt.Errorf("contract type %q requires file, inline, or explicit package source; source %q is unsupported", ref.Type, source.Type)
	}
	if !contractFilePath(root) {
		return ref, fmt.Errorf("invalid contract package root %q", root)
	}
	rootData, exists := files[root]
	if !exists {
		return ref, fmt.Errorf("contract package root %q is missing from files", root)
	}
	if source.SHA256 != "" && source.SHA256 != digest(rootData) {
		return ref, errors.New("contract package root hash mismatch")
	}
	entries := make([]schemaFile, 0, len(files))
	for name, data := range files {
		if !contractFilePath(name) {
			return ref, fmt.Errorf("invalid contract package path %q", name)
		}
		entries = append(entries, schemaFile{Path: name, SHA256: digest(data)})
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].Path < entries[j].Path })
	// Detect a file used as a directory before writing any package members.
	for name := range files {
		for parent := path.Dir(name); parent != "."; parent = path.Dir(parent) {
			if _, exists := files[parent]; exists {
				return ref, fmt.Errorf("contract package path %q is both a file and directory", parent)
			}
		}
	}
	setHash := contractPackageDigest(ref.Type, root, entries)
	base := "contracts/" + setHash + "/"
	manifest := schemaManifest{Profile: contractPackageProfile, Type: ref.Type, SetHash: setHash, Root: base + root}
	for _, entry := range entries {
		if err := writeContent(w.root, base+entry.Path, files[entry.Path]); err != nil {
			return ref, err
		}
		manifest.Files = append(manifest.Files, schemaFile{Path: base + entry.Path, SHA256: entry.SHA256})
	}
	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return ref, err
	}
	if err := writeContent(w.root, base+"manifest.json", append(data, '\n')); err != nil {
		return ref, err
	}
	ref.Source = artifact.SchemaSource{Type: "file", Path: filepath.Join(w.root, filepath.FromSlash(manifest.Root)), SHA256: digest(rootData), Format: source.Format}
	ref.AssetSHA = digest(rootData)
	return ref, nil
}

func validateContractPackageManifest(ref artifact.SchemaRef, manifest schemaManifest, base string) error {
	if manifest.Profile != contractPackageProfile || manifest.Type != ref.Type {
		return fmt.Errorf("contract %q package profile/type mismatch", ref.ID)
	}
	files := make([]schemaFile, 0, len(manifest.Files))
	for _, file := range manifest.Files {
		name := strings.TrimPrefix(file.Path, base+"/")
		if name == file.Path || !contractFilePath(name) {
			return fmt.Errorf("contract %q package file outside contract set", ref.ID)
		}
		files = append(files, schemaFile{Path: name, SHA256: file.SHA256})
	}
	root := strings.TrimPrefix(manifest.Root, base+"/")
	if !contractFilePath(root) || contractPackageDigest(ref.Type, root, files) != manifest.SetHash {
		return fmt.Errorf("contract %q package content identity mismatch", ref.ID)
	}
	return nil
}
